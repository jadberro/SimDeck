void SimDeckClient::runOta(const String& url, const String& sha, uint32_t size) {
  _updating = true;
  otaStatus("start", 0, nullptr);

  HTTPClient http;
  http.setTimeout(15000);
  if (!http.begin(url)) {
    otaStatus("fail", 0, "bad url");
    _updating = false;
    return;
  }

  int code = http.GET();
  if (code != HTTP_CODE_OK) {
    http.end();
    otaStatus("fail", 0, String(String("http ") + code).c_str());
    _updating = false;
    return;
  }

  int len = http.getSize();
  if (len <= 0) len = (int)size;
  if (len <= 0) {
    http.end();
    otaStatus("fail", 0, "unknown size");
    _updating = false;
    return;
  }

  if (!Update.begin(len)) {
    http.end();
    // Nearly always a partition scheme with no second app slot.
    otaStatus("fail", 0, "no ota partition");
    _updating = false;
    return;
  }

  mbedtls_sha256_context ctx;
  mbedtls_sha256_init(&ctx);
  SHA_STARTS(&ctx);

  WiFiClient* stream = http.getStreamPtr();
  uint8_t buf[1024];
  int written = 0;
  int lastPct = -5;
  uint32_t lastData = millis();
  bool failed = false;

  while (written < len) {
    size_t avail = stream->available();
    if (avail) {
      int n = stream->readBytes(buf, avail > sizeof(buf) ? sizeof(buf) : avail);
      if (n <= 0) break;
      SHA_UPDATE(&ctx, buf, n);
      if ((int)Update.write(buf, n) != n) {
        failed = true;
        break;
      }
      written += n;
      lastData = millis();

      int pct = (int)((written * 100L) / len);
      if (pct >= lastPct + 5) {
        lastPct = pct;
        otaStatus("progress", pct, nullptr);
      }
    } else {
      if (!http.connected() || millis() - lastData > 10000) {
        failed = true;
        break;
      }
      delay(1);
    }
  }
  http.end();

  uint8_t digest[32];
  SHA_FINISH(&ctx, digest);
  mbedtls_sha256_free(&ctx);

  char hex[65];
  for (int i = 0; i < 32; i++) sprintf(hex + i * 2, "%02x", digest[i]);
  hex[64] = 0;

  if (failed || written != len) {
    Update.abort();
    otaStatus("fail", 0, "transfer incomplete");
    _updating = false;
    return;
  }

  // Verify before committing. A corrupt image that passes Update.end()
  // bricks the module until someone gets a USB cable to it.
  if (sha.length() == 64 && !sha.equalsIgnoreCase(hex)) {
    Update.abort();
    otaStatus("fail", 0, "sha256 mismatch");
    _updating = false;
    return;
  }

  if (!Update.end(true)) {
    otaStatus("fail", 0, String(Update.errorString()).c_str());
    _updating = false;
    return;
  }

  otaStatus("ok", 100, nullptr);
  delay(250);            // let the datagram leave before we go down
  ESP.restart();
}

