#include "SimDeckClient.h"

#include <HTTPClient.h>
#include <Update.h>
#include <WiFi.h>
#include <math.h>

#include "mbedtls/sha256.h"

// Arduino-ESP32 v3 moved to IDF 5.x and dropped the _ret suffixed mbedtls
// entry points. v2 still needs them.
#if defined(ESP_ARDUINO_VERSION_MAJOR) && ESP_ARDUINO_VERSION_MAJOR >= 3
  #define SHA_STARTS(c)        mbedtls_sha256_starts((c), 0)
  #define SHA_UPDATE(c, b, n)  mbedtls_sha256_update((c), (b), (n))
  #define SHA_FINISH(c, o)     mbedtls_sha256_finish((c), (o))
#else
  #define SHA_STARTS(c)        mbedtls_sha256_starts_ret((c), 0)
  #define SHA_UPDATE(c, b, n)  mbedtls_sha256_update_ret((c), (b), (n))
  #define SHA_FINISH(c, o)     mbedtls_sha256_finish_ret((c), (o))
#endif

static const uint32_t HELLO_INTERVAL = 3000;
static const uint32_t HELLO_IDLE     = 15000;
static const uint32_t PING_INTERVAL  = 2000;
static const uint32_t DATA_TIMEOUT   = 1500;

// ---------------------------------------------------------------------------
// minimal JSON field extraction
//
// Every inbound message is generated by our own hub, so a full parser buys
// nothing. These handle exactly the shapes the hub emits.
// ---------------------------------------------------------------------------

static String jsonStr(const char* src, const char* key) {
  String pat = String("\"") + key + "\":\"";
  const char* p = strstr(src, pat.c_str());
  if (!p) return String();
  p += pat.length();
  const char* e = strchr(p, '"');
  if (!e) return String();
  return String(p).substring(0, e - p);
}

static uint32_t jsonNum(const char* src, const char* key) {
  String pat = String("\"") + key + "\":";
  const char* p = strstr(src, pat.c_str());
  if (!p) return 0;
  return (uint32_t)strtoul(p + pat.length(), nullptr, 10);
}

static String escapeJson(const char* s) {
  if (!s) return "";
  String res = "";
  while (*s) {
    if (*s == '"') res += "\\\"";
    else if (*s == '\\') res += "\\\\";
    else res += *s;
    s++;
  }
  return res;
}

