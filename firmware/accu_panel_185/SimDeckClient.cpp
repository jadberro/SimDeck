void SimDeckClient::begin(const char* moduleId, const char* moduleType,
                         const char* displayName, const char* fwVersion,
                         const char* const* names, uint8_t count,
                         float rateHz, const char* hubIp) {
  _id = moduleId;
  _type = moduleType;
  _name = displayName;
  _fw = fwVersion;
  _names = names;
  _count = count > SIMDECK_MAX_SLOTS ? SIMDECK_MAX_SLOTS : count;
  _rate = rateHz;

  for (uint8_t i = 0; i < SIMDECK_MAX_SLOTS; i++) _values[i] = NAN;

  if (hubIp && *hubIp) {
    if (_hubIp.fromString(hubIp)) {
      _haveHub = true;
      Serial.printf("[SimDeck] Configured Hub IP: %s\n", hubIp);
    }
  }

  _udp.begin(SIMDECK_MODULE_PORT);
  Serial.printf("[SimDeck] Listening on UDP %d\n", SIMDECK_MODULE_PORT);
  sendHello();
}

void SimDeckClient::sendCtrl(const String& json) {
  // Before the hub is known, broadcast. Its IP never has to be compiled in.
  if (_haveHub) {
    _udp.beginPacket(_hubIp, SIMDECK_CTRL_PORT);
    _udp.print(json);
    _udp.endPacket();
  } else {
    IPAddress dest = WiFi.localIP();
    dest[3] = 255;
    _udp.beginPacket(dest, SIMDECK_CTRL_PORT);
    _udp.print(json);
    _udp.endPacket();

    // Also send to 255.255.255.255 in case router drops directed broadcast
    _udp.beginPacket(IPAddress(255, 255, 255, 255), SIMDECK_CTRL_PORT);
    _udp.print(json);
    _udp.endPacket();
  }
}

void SimDeckClient::sendHello() {
  String msg = "{\"t\":\"hello\",\"id\":\"";
  msg += escapeJson(_id);
  msg += "\",\"type\":\"";
  msg += escapeJson(_type);
  msg += "\",\"name\":\"";
  msg += escapeJson(_name);
  msg += "\",\"fw\":\"";
  msg += escapeJson(_fw);
  msg += "\",\"rate\":";
  msg += String(_rate, 0);
  msg += ",\"sub\":[";
  for (uint8_t i = 0; i < _count; i++) {
    if (i) msg += ",";
    msg += "\"";
    msg += escapeJson(_names[i]);
    msg += "\"";
  }
  msg += "]}";
  sendCtrl(msg);
  Serial.printf("[SimDeck] Announce sent to %s:%d\n",
                _haveHub ? _hubIp.toString().c_str() : "broadcast", SIMDECK_CTRL_PORT);
  _lastHello = millis();
}

void SimDeckClient::sendPing() {
  if (!_haveHub) return;
  sendCtrl(String("{\"t\":\"ping\",\"id\":\"") + _id + "\"}");
  _lastPing = millis();
}

void SimDeckClient::sendEvent(const char* inputId, float value) {
  if (!_haveHub) return;
  String msg = "{\"t\":\"ev\",\"id\":\"";
  msg += _id;
  msg += "\",\"in\":\"";
  msg += inputId;
  msg += "\",\"v\":";
  msg += String(value, 4);
  msg += "}";
  sendCtrl(msg);
}

void SimDeckClient::otaStatus(const char* state, int pct, const char* err) {
  String msg = "{\"t\":\"ota_status\",\"id\":\"";
  msg += _id;
  msg += "\",\"state\":\"";
  msg += state;
  msg += "\",\"pct\":";
  msg += pct;
  if (err && *err) {
    msg += ",\"err\":\"";
    msg += err;
    msg += "\"";
  }
  msg += "}";
  sendCtrl(msg);
}

