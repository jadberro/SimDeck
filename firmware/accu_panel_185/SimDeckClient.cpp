void SimDeckClient::handleFrame(const uint8_t* buf, int len) {
  if (len < SIMDECK_HEADER_LEN) return;
  if (buf[0] != SIMDECK_DATA_MAGIC || buf[1] != SIMDECK_PROTO_VERSION) return;

  uint16_t seq;
  memcpy(&seq, buf + 2, 2);
  uint8_t count = buf[4];
  uint8_t flags = buf[5];

  // Drop out-of-order datagrams. The signed diff handles wraparound.
  int16_t diff = (int16_t)(seq - _lastSeq);
  if (_lastFrame && diff <= 0) return;
  _lastSeq = seq;

  if (len < SIMDECK_HEADER_LEN + 4 * count) return;
  if (count > SIMDECK_MAX_SLOTS) count = SIMDECK_MAX_SLOTS;

  for (uint8_t i = 0; i < count; i++) {
    float v;
    memcpy(&v, buf + SIMDECK_HEADER_LEN + 4 * i, 4);
    // NaN means the hub could not resolve it - hold the last good value.
    if (!isnan(v)) _values[i] = v;
  }

  _flags = flags;
  _lastFrame = millis();
  _linked = true;
}

void SimDeckClient::handleJson(const char* text) {
  if (strstr(text, "\"welcome\"")) {
    _linked = true;
    Serial.printf("[SimDeck] Linked! Received welcome from Hub at %s\n", _hubIp.toString().c_str());
    return;
  }
  if (strstr(text, "\"identify\"")) {
    Serial.println("[SimDeck] Identify command received");
    if (_identify) _identify();
    return;
  }
  if (strstr(text, "\"t\":\"ota\"")) {
    String url = jsonStr(text, "url");
    String sha = jsonStr(text, "sha256");
    uint32_t size = jsonNum(text, "size");
    if (url.length()) runOta(url, sha, size);
    return;
  }
}

void SimDeckClient::poll() {
  int sz = _udp.parsePacket();
  while (sz > 0) {
    static uint8_t buf[SIMDECK_HEADER_LEN + 4 * SIMDECK_MAX_SLOTS + 512];
    int len = _udp.read(buf, sizeof(buf) - 1);
    if (len > 0) {
      if (!_haveHub || _hubIp != _udp.remoteIP()) {
        _hubIp = _udp.remoteIP();
        _haveHub = true;
        Serial.printf("[SimDeck] Discovered Hub at %s\n", _hubIp.toString().c_str());
      }
      if (buf[0] == SIMDECK_DATA_MAGIC) {
        handleFrame(buf, len);
      } else {
        buf[len] = 0;
        handleJson((const char*)buf);
      }
    }
    sz = _udp.parsePacket();
  }

  uint32_t now = millis();

  // Re-announce periodically. Cheap, and it means a hub restart or a module
  // reboot both recover without anyone touching anything.
  if (now - _lastHello > (_linked ? HELLO_IDLE : HELLO_INTERVAL)) sendHello();
  if (now - _lastPing > PING_INTERVAL) sendPing();
  if (_lastFrame && now - _lastFrame > DATA_TIMEOUT) _linked = false;
}

float SimDeckClient::value(uint8_t slot) const {
  if (slot >= _count) return NAN;
  return _values[slot];
}

bool SimDeckClient::live() const {
  return _linked && (_flags & SIMDECK_FLAG_SIM_OK);
}
